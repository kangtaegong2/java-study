package operator.ex;

public class OperationEx3 {
    public static void main(String[] args) {
        int score = 80;
        boolean a = score >= 80 && score <= 100; //boolean이란 true 또는 false 두 가지 값만 저장할 수 있는 데이터 타입(종류)
        //변수는 보통 result 으로 많이 쓰임 &&는 그리고(AND)를 뜻하는 논리 연산자임
        System.out.println(a);

    }
}
